static const mm::Mouse* dryMouse = nullptr;
static const char* dryError = "no error";

// Move timings in the dry run, so a search run takes a few seconds on the bench.
static const uint32_t DRY_CELL_MS = 30;
static const uint32_t DRY_TURN_MS = 20;
static const uint32_t DRY_TURN_AROUND_MS = 40;

static bool dryWall(uint8_t c, mm::Dir d) { return (pgm_read_byte(&DRY_MAZE[c]) >> d) & 1; }

// Wait in small slices so a button press stops the "wheels" promptly.
static bool dryWait(uint32_t ms) {
  const uint32_t t0 = millis();
  while (millis() - t0 < ms) {
    if (runAbortRequested()) return false;
    delay(5);
  }
  return true;
}

void dryRunAttach(const mm::Mouse* m) { dryMouse = m; }

const char* begin() {
  boardUiBegin();
  led(0, 0, 0);
  return nullptr;
}

const char* lastError() { return dryError; }

const char* runBegin(int) {
  if (!dryMouse) { dryError = "dry run: dryRunAttach() was not called"; return dryError; }
  return nullptr;
}
void runEnd() {}

bool readWalls(bool& left, bool& front, bool& right) {
  if (!dryMouse) return false;
  const uint8_t c = dryMouse->cell;
  const mm::Dir h = dryMouse->heading;
  left  = dryWall(c, mm::leftOf(h));
  front = dryWall(c, h);
  right = dryWall(c, mm::rightOf(h));
  return true;
}

bool forwardOneCell(int) { return dryWait(DRY_CELL_MS); }
bool turnLeft(int)       { return dryWait(DRY_TURN_MS); }
bool turnRight(int)      { return dryWait(DRY_TURN_MS); }
bool turnAround(int)     { return dryWait(DRY_TURN_AROUND_MS); }

void led(uint8_t r, uint8_t g, uint8_t b) { boardLedWrite(r, g, b); }
bool buttonPressed() { return boardButtonPressed(); }

